"""Adapter merge: plan, generated Unsloth script, and execution.

The merge script loads the adapter with Unsloth and writes 16-bit weights with
``save_pretrained_merged(..., save_method="merged_16bit")``, the input llama.cpp expects.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from string import Template
from typing import Any

from msft.config import MsftError, RunConfig

MERGE_SCRIPT_NAME = "merge_script.py"
MERGE_META_NAME = "merge_meta.json"
SAVE_METHOD = "merged_16bit"


def _adapter_files(cfg: RunConfig) -> dict[str, bool]:
    """Which adapter artifacts are on disk right now."""
    adapter = cfg.adapter_path
    return {
        "adapter_exists": adapter.is_dir(),
        "adapter_config": (adapter / "adapter_config.json").is_file(),
        "adapter_weights": (adapter / "adapter_model.safetensors").is_file()
        or (adapter / "adapter_model.bin").is_file(),
    }


def plan(cfg: RunConfig) -> dict[str, Any]:
    """Paths, save method and on-disk state for merging the adapter into bf16 weights."""
    script_path = cfg.output_path / MERGE_SCRIPT_NAME
    checks = _adapter_files(cfg)
    notes: list[str] = []
    if not checks["adapter_exists"]:
        notes.append(f"{cfg.adapter_path} does not exist yet; run `msft train --execute`")
    elif not checks["adapter_config"]:
        notes.append(f"{cfg.adapter_path} has no adapter_config.json; merge would fail")
    if cfg.merged_path.exists():
        notes.append(f"{cfg.merged_path} already exists and would be overwritten")
    return {
        "stage": "merge",
        "name": cfg.name,
        "model": cfg.model.id,
        "adapter": str(cfg.adapter_path),
        "merged": str(cfg.merged_path),
        "save_method": SAVE_METHOD,
        "dtype": "bfloat16",
        "max_seq_length": cfg.train.max_seq_length,
        "script": str(script_path),
        "command": [sys.executable, str(script_path)],
        "install": "uv pip install -e '.[train]'",
        "checks": checks,
        "notes": notes,
    }


_SCRIPT = Template(
    '''#!/usr/bin/env python
"""Adapter merge generated by `msft merge` -- standalone, imports nothing from msft.

Adapter: $ADAPTER_DIR
Merged:  $MERGED_DIR (bfloat16, $SAVE_METHOD)
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

# Unsloth has to be imported before transformers so its patches land first.
from unsloth import FastLanguageModel

BASE_MODEL = $MODEL_ID
REVISION = $MODEL_REVISION
ADAPTER_DIR = Path($ADAPTER_DIR)
MERGED_DIR = Path($MERGED_DIR)
META_FILE = Path($META_FILE)
SAVE_METHOD = $SAVE_METHOD
MAX_SEQ_LENGTH = $MAX_SEQ
LOAD_IN_4BIT = $LOAD_IN_4BIT


def fail(message: str) -> int:
    """Report a fatal problem without a traceback."""
    print(f"error: {message}", file=sys.stderr)
    return 1


def main() -> int:
    """Load base + adapter with Unsloth, merge and save bf16 weights."""
    config_file = ADAPTER_DIR / "adapter_config.json"
    if not config_file.is_file():
        return fail(f"{config_file} is missing; run `msft train --execute` first")

    adapter_meta = json.loads(config_file.read_text(encoding="utf-8"))
    declared = adapter_meta.get("base_model_name_or_path")
    if declared and declared != BASE_MODEL:
        print(
            f"note: adapter was trained on {declared}, config says {BASE_MODEL}; "
            "using the adapter's base model",
            file=sys.stderr,
        )

    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=str(ADAPTER_DIR),
        max_seq_length=MAX_SEQ_LENGTH,
        dtype=None,
        load_in_4bit=LOAD_IN_4BIT,
    )

    MERGED_DIR.mkdir(parents=True, exist_ok=True)
    model.save_pretrained_merged(str(MERGED_DIR), tokenizer, save_method=SAVE_METHOD)
    tokenizer.save_pretrained(str(MERGED_DIR))

    meta = {
        "model": declared or BASE_MODEL,
        "revision": REVISION,
        "adapter": str(ADAPTER_DIR),
        "merged": str(MERGED_DIR),
        "save_method": SAVE_METHOD,
        "dtype": "bfloat16",
        "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    META_FILE.parent.mkdir(parents=True, exist_ok=True)
    META_FILE.write_text(json.dumps(meta, indent=2, sort_keys=True) + "\\n", encoding="utf-8")
    print(f"merged weights written to {MERGED_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''
)


def _literal(value: object) -> str:
    """Python literal for a config value: `None` stays `None`, everything else is JSON."""
    return "None" if value is None else json.dumps(value)


def build_script(cfg: RunConfig) -> str:
    """The standalone merge script for `cfg`, ready to save and run with any python."""
    return _SCRIPT.substitute(
        MODEL_ID=json.dumps(cfg.model.id),
        MODEL_REVISION=_literal(cfg.model.revision),
        ADAPTER_DIR=json.dumps(str(cfg.adapter_path)),
        MERGED_DIR=json.dumps(str(cfg.merged_path)),
        META_FILE=json.dumps(str(cfg.output_path / MERGE_META_NAME)),
        SAVE_METHOD=json.dumps(SAVE_METHOD),
        MAX_SEQ=cfg.train.max_seq_length,
        LOAD_IN_4BIT=cfg.model.load_in_4bit,
    )


def _log(message: str) -> None:
    """Progress line on stderr, so a `--json` run keeps stdout to one object."""
    print(message, file=sys.stderr)


def _require_adapter(cfg: RunConfig) -> None:
    """Raise unless a trainable adapter is on disk where the config says it is."""
    checks = _adapter_files(cfg)
    if not checks["adapter_exists"] or not checks["adapter_config"]:
        raise MsftError(
            f"no adapter at {cfg.adapter_path}; run `msft train --execute` first "
            "(or point output_dir at an existing run)"
        )


def run(cfg: RunConfig, *, execute: bool = False) -> dict[str, Any]:
    """Return the plan; with `execute=True` write output/merge_script.py and run it.

    Nothing is written when `execute` is false: a dry run must not create artifacts.
    """
    result = plan(cfg)
    result["executed"] = False
    if not execute:
        return result

    _require_adapter(cfg)
    script_path = Path(result["script"])
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(build_script(cfg), encoding="utf-8")
    _log(f"wrote {script_path}")
    _log(f"$ {sys.executable} {script_path}")

    completed = subprocess.run([sys.executable, str(script_path)], check=False)
    if completed.returncode != 0:
        raise MsftError(
            f"merge script exited {completed.returncode}; read the log above, fix the "
            f"cause and re-run: {script_path}"
        )
    config_file = cfg.merged_path / "config.json"
    if not config_file.is_file():
        raise MsftError(
            f"merge exited 0 but {config_file} is missing; save_pretrained_merged did nothing"
        )
    result["executed"] = True
    result["returncode"] = completed.returncode
    return result
